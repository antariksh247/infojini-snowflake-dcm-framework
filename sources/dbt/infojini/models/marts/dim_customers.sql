SELECT
  C.CUSTOMER_ID,
  C.FULL_NAME,
  C.CITY,
  C.IS_ACTIVE,
  COUNT(O.ORDER_ID)  AS TOTAL_ORDERS,
  MIN(O.ORDER_TS)    AS FIRST_ORDER_TS,
  MAX(O.ORDER_TS)    AS LAST_ORDER_TS
FROM {{ ref('stg_customers') }} C
LEFT JOIN {{ ref('stg_orders') }} O
  ON O.CUSTOMER_ID = C.CUSTOMER_ID AND O.STATUS = 'COMPLETED'
GROUP BY C.CUSTOMER_ID, C.FULL_NAME, C.CITY, C.IS_ACTIVE

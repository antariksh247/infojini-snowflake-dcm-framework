-- Silver: conformed customer table, a helper function and the load procedure.
-- Reads the shared Bronze ({{ bronze_db }}); the deployer role has Bronze READ (setup/03).

DEFINE TABLE {{ db('SILVER') }}.CORE.CUSTOMERS (
  CUSTOMER_ID  NUMBER,
  FULL_NAME    VARCHAR,
  CITY         VARCHAR,
  IS_ACTIVE    BOOLEAN,
  UPDATED_AT   TIMESTAMP_NTZ
)
COMMENT = 'Conformed customers, loaded by SP_LOAD_CUSTOMERS';

DEFINE FUNCTION {{ db('SILVER') }}.CORE.FN_FULL_NAME(FIRST_NAME VARCHAR, LAST_NAME VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
  INITCAP(TRIM(FIRST_NAME)) || ' ' || INITCAP(TRIM(LAST_NAME))
$$;

DEFINE PROCEDURE {{ db('SILVER') }}.CORE.SP_LOAD_CUSTOMERS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO {{ db('SILVER') }}.CORE.CUSTOMERS T
  USING (
    SELECT CUSTOMER_ID,
           {{ db('SILVER') }}.CORE.FN_FULL_NAME(FIRST_NAME, LAST_NAME) AS FULL_NAME,
           UPPER(CITY) AS CITY,
           IS_ACTIVE
    FROM {{ bronze_db }}.SOURCE_RAW.CUSTOMERS
  ) S
  ON T.CUSTOMER_ID = S.CUSTOMER_ID
  WHEN MATCHED THEN UPDATE SET
    T.FULL_NAME = S.FULL_NAME, T.CITY = S.CITY, T.IS_ACTIVE = S.IS_ACTIVE,
    T.UPDATED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
  WHEN NOT MATCHED THEN INSERT (CUSTOMER_ID, FULL_NAME, CITY, IS_ACTIVE, UPDATED_AT)
    VALUES (S.CUSTOMER_ID, S.FULL_NAME, S.CITY, S.IS_ACTIVE, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ);
  RETURN 'CUSTOMERS merged: ' || SQLROWCOUNT || ' rows';
END;
$$;

-- Access
GRANT SELECT ON TABLE {{ db('SILVER') }}.CORE.CUSTOMERS TO DATABASE ROLE {{ db('SILVER') }}.READ;
GRANT USAGE ON FUNCTION {{ db('SILVER') }}.CORE.FN_FULL_NAME(VARCHAR, VARCHAR) TO DATABASE ROLE {{ db('SILVER') }}.READ;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON TABLE {{ db('SILVER') }}.CORE.CUSTOMERS TO DATABASE ROLE {{ db('SILVER') }}.WRITE;
GRANT USAGE ON PROCEDURE {{ db('SILVER') }}.CORE.SP_LOAD_CUSTOMERS() TO DATABASE ROLE {{ db('SILVER') }}.WRITE;

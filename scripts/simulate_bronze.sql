  CUSTOMER_ID   NUMBER,
  FIRST_NAME    VARCHAR,
  LAST_NAME     VARCHAR,
  CITY          VARCHAR,
  IS_ACTIVE     BOOLEAN,
  _LOADED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Run as : ACCOUNTADMIN (the script switches roles itself)
-- Needs  : setup/01_platform.sql done
-- Re-run : safe (tables are recreated with the same dummy rows)
-- Purpose: simulate the external Bronze layer.
--   In a real project this DB is filled by Fivetran / a data share,
--   NOT by DCM. Here INFOJINI_LOADER plays the role of that tool.

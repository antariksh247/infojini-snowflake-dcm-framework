USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS INFOJINI_BRONZE_DB
  DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'Shared Bronze (external source, read-only for all envs). Simulated in the POC.';
GRANT OWNERSHIP ON DATABASE INFOJINI_BRONZE_DB TO ROLE INFOJINI_LOADER COPY CURRENT GRANTS;

USE ROLE INFOJINI_LOADER;
USE WAREHOUSE INFOJINI_LOAD_WH;

CREATE SCHEMA IF NOT EXISTS INFOJINI_BRONZE_DB.SOURCE_RAW COMMENT = 'Raw tables as delivered by the source';
DROP SCHEMA IF EXISTS INFOJINI_BRONZE_DB.PUBLIC;


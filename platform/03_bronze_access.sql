-- =====================================================================
-- platform/03_bronze_access.sql
-- Run as : ACCOUNTADMIN (the script switches roles itself)
-- Needs  : Bronze DB exists (platform/poc/simulate_bronze.sql in the POC,
--          Fivetran / data share in a real project)
-- Re-run : safe
-- Purpose: read-only access to Bronze for every environment
--   - database role INFOJINI_BRONZE_DB.READ (SELECT on all + future tables/views)
--   - granted to the 3 deployers (DCM objects read Bronze: procs, views, tasks)
--     and to engineers / scientists. Analysts, BI and app: no Bronze.
-- =====================================================================

USE ROLE INFOJINI_LOADER;   -- owner of Bronze
CREATE DATABASE ROLE IF NOT EXISTS INFOJINI_BRONZE_DB.READ COMMENT = 'Read-only on all Bronze data';

USE ROLE SECURITYADMIN;     -- MANAGE GRANTS: needed for future grants
GRANT USAGE  ON DATABASE INFOJINI_BRONZE_DB                    TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT SELECT ON ALL TABLES     IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT SELECT ON FUTURE TABLES  IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT SELECT ON ALL VIEWS      IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE INFOJINI_BRONZE_DB  TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;

GRANT DATABASE ROLE INFOJINI_BRONZE_DB.READ TO ROLE INFOJINI_DEV_DEPLOYER;
GRANT DATABASE ROLE INFOJINI_BRONZE_DB.READ TO ROLE INFOJINI_STAGE_DEPLOYER;
GRANT DATABASE ROLE INFOJINI_BRONZE_DB.READ TO ROLE INFOJINI_PROD_DEPLOYER;
GRANT DATABASE ROLE INFOJINI_BRONZE_DB.READ TO ROLE INFOJINI_DATA_ENGINEER;   -- DATA_ADMIN inherits
GRANT DATABASE ROLE INFOJINI_BRONZE_DB.READ TO ROLE INFOJINI_DATA_SCIENTIST;

-- Checks
SHOW GRANTS TO DATABASE ROLE INFOJINI_BRONZE_DB.READ;
SHOW GRANTS OF DATABASE ROLE INFOJINI_BRONZE_DB.READ;   -- expect 5 roles

USE ROLE INFOJINI_DATA_ENGINEER;
USE WAREHOUSE INFOJINI_ADMIN_WH;
SELECT COUNT(*) FROM INFOJINI_BRONZE_DB.SOURCE_RAW.ORDERS;   -- expect 6
